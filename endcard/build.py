"""Inline the prepared plates into a single self-contained HTML file.

Run from the repo root:  python3 endcard/build.py
"""
import base64
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent
ASSETS = ROOT / "assets"
OUT = ROOT.parent / "ustaad-endcard.html"

images = {p.stem: "data:image/png;base64," + base64.b64encode(p.read_bytes()).decode()
          for p in sorted(ASSETS.glob("*.png"))}
layout = json.loads((ASSETS / "layers.json").read_text())

block = ("/* Embedded assets, generated by endcard/build.py */\n"
         f"const ASSETS = {json.dumps(images, indent=0)};\n"
         f"const LAYOUT = {json.dumps(layout)};")

src = (ROOT / "src.html").read_text()
assert "/*__ASSETS__*/" in src
OUT.write_text(src.replace("/*__ASSETS__*/", block))
print(f"wrote {OUT} ({OUT.stat().st_size / 1e6:.2f} MB, {len(images)} plates)")
